"""Reports endpoints (frontend spec §18.10 / §14).

Reports are generated by the backend from database data and stored in
``report_runs``. Downloads are authenticated; PDF export is intentionally
not implemented in v1 (Arabic RTL PDF requires a shaping pipeline — see
IMPLEMENTATION_NOTES), CSV/JSON are fully supported.
"""
from __future__ import annotations

from datetime import UTC, datetime

import sqlalchemy as sa
from fastapi import APIRouter, Depends, Query, Request, Response
from pydantic import BaseModel

from app.webapi.dependencies import current_user, get_db, get_state, verify_csrf
from app.webapi.envelope import ApiError, envelope
from app.webapi import queries
from app.webapi.params import period_window
from app.persistence.models import ReportRunRow

router = APIRouter(prefix="/api/v1/reports", tags=["reports"])

REPORT_TYPES = {"daily", "weekly", "monthly", "custom", "strategy_contribution", "session_analysis", "rejected_opportunities"}


class CreateReportRequest(BaseModel):
    report_type: str = "weekly"
    from_: str | None = Query(None, alias="from")
    to: str | None = None


@router.get("")
def reports_list(request: Request, session=Depends(get_db), user=Depends(current_user)):
    return envelope(request, {"items": queries.reports_list(session)})


@router.post("")
def create_report(
    request: Request,
    body: CreateReportRequest,
    session=Depends(get_db),
    state=Depends(get_state),
    user=Depends(verify_csrf),
):
    from app.core.ids import new_uuid
    from app.persistence.database import dumps
    from app.reporting import metrics as perf

    report_type = body.report_type.lower()
    if report_type not in REPORT_TYPES:
        raise ApiError(422, "VALIDATION_ERROR", f"report_type must be one of {sorted(REPORT_TYPES)}", {"field": "report_type"})
    days_map = {"daily": 1, "weekly": 7, "monthly": 30, "custom": 7, "strategy_contribution": 30, "session_analysis": 30, "rejected_opportunities": 7}
    start, end = period_window({"daily": "today", "weekly": "7d", "monthly": "30d"}.get(report_type, "7d"), body.from_, body.to)
    portfolio = queries.get_portfolio(session)
    if portfolio is None:
        raise ApiError(409, "NO_DATA", "Portfolio not initialised — start the engine first")
    trades = queries._closed_trades_in_period(state, portfolio.id, start, end)
    content = {
        "period": {"from": queries.to_iso(start), "to": queries.to_iso(end), "timezone": "UTC"},
        "portfolio_start_balance": queries.fl(portfolio.initial_balance),
        "portfolio_end_balance": queries.fl(portfolio.current_balance),
        "metrics": queries._metrics_dict(perf.compute_metrics(trades)),
        "by_strategy": {k: queries._metrics_dict(perf.compute_metrics(v)) for k, v in queries.session_bucket(trades, lambda t: t.origin_strategy_id).items()},
        "by_session": {k: queries._metrics_dict(perf.compute_metrics(v)) for k, v in queries.session_bucket(trades, lambda t: t.entry_session_name).items()},
        "costs_total": round(sum((t.commission or 0) + (t.swap or 0) for t in trades), 2),
        "sample_note": "A single period is not conclusive evidence; treat metrics as indicative only (insufficient sample if noted).",
        "generated_by": user.username,
        "report_type": report_type,
    }
    row = ReportRunRow(
        id=new_uuid(),
        report_type=report_type,
        period_start_utc=start,
        period_end_utc=end,
        metrics_json=dumps(content),
    )
    with state.database.session() as write_session:
        write_session.add(row)
        write_session.flush()
    return envelope(request, {"report_id": row.id, "status": "ready", "report_type": report_type})


@router.get("/{report_id}")
def report_detail(request: Request, report_id: str, session=Depends(get_db), user=Depends(current_user)):
    row = session.get(ReportRunRow, report_id)
    if row is None:
        raise ApiError(404, "NOT_FOUND", "Report not found")
    return envelope(
        request,
        {
            "report_id": row.id,
            "report_type": row.report_type,
            "period_start": queries.to_iso(row.period_start_utc),
            "period_end": queries.to_iso(row.period_end_utc),
            "generated_at": queries.to_iso(row.generated_at_utc),
            "status": "ready" if row.metrics_json else "failed",
            "content": queries.jload(row.metrics_json),
        },
    )


@router.get("/{report_id}/download")
def report_download(
    request: Request,
    report_id: str,
    format: str = Query("json", pattern="^(json|csv)$"),
    session=Depends(get_db),
    user=Depends(current_user),
):
    row = session.get(ReportRunRow, report_id)
    if row is None:
        raise ApiError(404, "NOT_FOUND", "Report not found")
    content = queries.jload(row.metrics_json, {}) or {}
    if format == "json":
        import json

        return Response(
            json.dumps(content, ensure_ascii=False, indent=2),
            media_type="application/json",
            headers={"Content-Disposition": f'attachment; filename="report_{row.id[:8]}.json"'},
        )
    lines = ["section,key,value"]
    metrics = content.get("metrics", {})
    for k, v in metrics.items():
        lines.append(f"metrics,{k},{v if v is not None else ''}")
    for section in ("by_strategy", "by_session"):
        for bucket, values in (content.get(section) or {}).items():
            for k, v in values.items():
                lines.append(f"{section}:{bucket},{k},{v if v is not None else ''}")
    return Response(
        "\n".join(lines),
        media_type="text/csv; charset=utf-8",
        headers={"Content-Disposition": f'attachment; filename="report_{row.id[:8]}.csv"'},
    )
